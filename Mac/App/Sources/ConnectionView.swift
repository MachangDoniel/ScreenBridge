import SwiftUI
import ScreenBridgeMacCore
import ScreenBridgeProtocol

struct ConnectionView: View {
    @ObservedObject var model: AppModel

    var body: some View {
        Form {
            Section("Receiver") {
                LabeledContent("Name", value: model.receiverName)
                LabeledContent("Receiver ID") { Text(model.identity?.receiverID ?? "—").font(.callout.monospaced()).textSelection(.enabled) }
                LabeledContent("Status") { Text(listenerText) }
                LabeledContent("Bonjour service", value: WireProtocol.serviceType)
                Text("Only the public receiver ID is advertised. Apps authenticate with a per-project TLS pre-shared key generated by the build phase.")
                    .font(.caption).foregroundStyle(.secondary)
                if let e = model.startupError { Text(e).foregroundStyle(.red) }
            }

            Section("Connected apps") {
                if model.sessions.isEmpty {
                    Text("No apps connected. Run a Debug build from Xcode on a device or simulator on this network.").foregroundStyle(.secondary)
                }
                ForEach(model.sessions) { s in
                    VStack(alignment: .leading, spacing: 2) {
                        Text("\(s.hello.appName) — \(s.projectName)").fontWeight(.medium)
                        Text("\(s.hello.deviceModel)\(s.hello.isSimulator ? " Simulator" : "") · iOS \(s.hello.systemVersion) · connected \(s.connectedAt.formatted(date: .omitted, time: .shortened))")
                            .font(.caption).foregroundStyle(.secondary)
                    }
                }
            }

            Section("Projects and credentials") {
                if model.projects.isEmpty {
                    Text("No projects yet. Builds register their repository automatically.").foregroundStyle(.secondary)
                }
                ForEach(model.projects) { p in
                    VStack(alignment: .leading, spacing: 4) {
                        Text(p.name).fontWeight(.medium)
                        Text(p.rootPath).font(.caption.monospaced()).foregroundStyle(.secondary).textSelection(.enabled)
                        ForEach(model.credentials.filter { $0.projectID == p.id }) { c in
                            HStack {
                                Text("\(c.appBundleIdentifier) · \(c.id)").font(.caption.monospaced())
                                Spacer()
                                if c.isActive {
                                    Text(c.lastUsedAt.map { "used \($0.formatted(.relative(presentation: .named)))" } ?? "never used").font(.caption).foregroundStyle(.secondary)
                                    Button("Revoke", role: .destructive) { model.revoke(c) }.controlSize(.small)
                                } else {
                                    Text("revoked").font(.caption).foregroundStyle(.secondary)
                                }
                            }
                        }
                    }
                    .padding(.vertical, 2)
                }
            }

            Section("Claude (MCP)") {
                StatusLine(ok: model.mcpInstalled, text: model.mcpInstalled ? "Server command: \(ShimInstaller.mcpCommandPath(home: model.home))" : "MCP command not installed.")
                StatusLine(ok: model.claudeDesktopConfigured, text: model.claudeDesktopConfigured ? "Claude Desktop config includes “screenbridge”." : "Not in Claude Desktop config yet.")
                HStack {
                    Button("Copy Claude Desktop configuration") { model.copyMCPConfig() }
                    Spacer()
                }
                Text("Restart Claude Desktop after editing its configuration. For Claude Code: claude mcp add screenbridge -- \"\(ShimInstaller.mcpCommandPath(home: model.home))\"")
                    .font(.caption).foregroundStyle(.secondary).textSelection(.enabled)
            }

            Section("This Mac") {
                LabeledContent("Notifications") {
                    Text(model.notificationsAuthorized == true ? "Allowed" : model.notificationsAuthorized == false ? "Off — the inbox still works" : "Not determined")
                }
                LabeledContent("Data folder") {
                    Button(model.home.root.path) { model.openStoreFolder() }.buttonStyle(.link)
                }
                Text("Reports are kept for 30 days (up to 200). Delete individual reports from the list.")
                    .font(.caption).foregroundStyle(.secondary)
            }
        }
        .formStyle(.grouped)
        .navigationTitle("Connection")
        .onAppear { model.refresh() }
    }

    private var listenerText: String {
        switch model.listenerStatus {
        case .ready(let port): return "Listening on port \(port)"
        case .starting: return "Starting…"
        case .failed(let e): return "Failed: \(e)"
        case .stopped: return "Stopped"
        }
    }
}
